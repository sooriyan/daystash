import { NextResponse } from 'next/server';
import { db, schema } from '@/lib/db';
import { extractAuthUserId } from '@/lib/auth';
import { DeviceRegisterInputSchema } from '@/lib/validators/device';

const { userDevices, users } = schema;

/**
 * POST /api/devices/register
 * Upserts a client device's Expo Push Token into user_devices.
 */
export async function POST(request: Request) {
  try {
    let bodyJson: unknown;
    try {
      bodyJson = await request.json();
    } catch {
      return NextResponse.json(
        { error: 'Invalid JSON payload' },
        { status: 400 }
      );
    }

    const parseResult = DeviceRegisterInputSchema.safeParse(bodyJson);
    if (!parseResult.success) {
      return NextResponse.json(
        {
          error: 'Validation Error',
          issues: parseResult.error.issues,
        },
        { status: 400 }
      );
    }

    const { expoPushToken, platform, userId: bodyUserId } = parseResult.data;

    // Resolve authenticated user ID
    const userId = extractAuthUserId(request) || bodyUserId;
    if (!userId) {
      return NextResponse.json(
        { error: 'Unauthorized: Missing user authentication or userId' },
        { status: 401 }
      );
    }

    // Ensure user record exists in users table to satisfy foreign key constraint
    await db
      .insert(users)
      .values({
        id: userId,
        email: `${userId}@autogenerated.daystash.local`,
        createdAt: new Date(),
        updatedAt: new Date(),
      })
      .onConflictDoNothing({ target: users.id });

    // Upsert device registration
    const [upsertedRecord] = await db
      .insert(userDevices)
      .values({
        id: crypto.randomUUID(),
        userId,
        expoPushToken,
        platform,
        createdAt: new Date(),
        updatedAt: new Date(),
      })
      .onConflictDoUpdate({
        target: [userDevices.userId, userDevices.expoPushToken],
        set: {
          platform,
          updatedAt: new Date(),
        },
      })
      .returning();

    return NextResponse.json(
      {
        success: true,
        device: {
          id: upsertedRecord.id,
          userId: upsertedRecord.userId,
          expoPushToken: upsertedRecord.expoPushToken,
          platform: upsertedRecord.platform,
          updatedAt: upsertedRecord.updatedAt.toISOString(),
        },
      },
      { status: 200 }
    );
  } catch (error) {
    console.error('[API /api/devices/register] Internal Error:', error);
    return NextResponse.json(
      {
        error: 'Internal Server Error',
        message: error instanceof Error ? error.message : 'Unknown error',
      },
      { status: 500 }
    );
  }
}
