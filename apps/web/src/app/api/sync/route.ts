import { NextResponse } from 'next/server';
import { z } from 'zod';
import { eq, and, gt } from 'drizzle-orm';
import { db, schema } from '@/lib/db';
import { extractAuthUserId } from '@/lib/auth';
import {
  scheduleReminderJob,
  cancelReminderJob,
  enqueueSilentPushJob,
} from '@/lib/queues';
import {
  SyncRequestSchema,
  ReminderSyncMutationSchema,
  type SyncResponse,
  type SyncConflict,
  type ReminderServerDelta,
} from '@repo/core/validators/sync';
import type { ReminderStatus } from '@repo/core/schema/postgres';

const { reminders, users, userDevices } = schema;

/**
 * Flexible sync payload schema that accepts both `mutations` and `changes`
 * for broad client compatibility.
 */
const InboundSyncPayloadSchema = z.union([
  SyncRequestSchema,
  z
    .object({
      deviceId: z.string().min(1, 'Device identifier is required'),
      lastSyncedAt: z.string().datetime().nullable().optional(),
      clientTimestamp: z
        .string()
        .datetime()
        .optional()
        .default(() => new Date().toISOString()),
      changes: z.array(ReminderSyncMutationSchema).default([]),
    })
    .transform((data) => ({
      deviceId: data.deviceId,
      lastSyncedAt: data.lastSyncedAt,
      clientTimestamp: data.clientTimestamp,
      mutations: data.changes,
    })),
]);

interface PendingJobUpdate {
  id: string;
  title: string;
  status: ReminderStatus;
  nextTriggerUtc: Date | null;
}

/**
 * POST /api/sync
 * Bidirectional delta synchronization with Optimistic Concurrency Control (OCC)
 * and Last-Write-Wins (LWW) conflict resolution fallback.
 */
export async function POST(request: Request) {
  try {
    let bodyJson: unknown;
    try {
      bodyJson = await request.json();
    } catch {
      return NextResponse.json(
        { error: 'Invalid JSON payload' },
        { status: 400 }
      );
    }

    // 1. Validate payload using Zod schema
    const parseResult = InboundSyncPayloadSchema.safeParse(bodyJson);
    if (!parseResult.success) {
      return NextResponse.json(
        {
          error: 'Validation Error',
          issues: parseResult.error.issues,
        },
        { status: 400 }
      );
    }

    const { deviceId, lastSyncedAt, mutations } = parseResult.data;

    // 2. Resolve authenticated user identity
    const userId = extractAuthUserId(request);
    if (!userId) {
      return NextResponse.json(
        { error: 'Unauthorized: Missing user authentication' },
        { status: 401 }
      );
    }

    // Ensure user record exists in PostgreSQL users table
    await db
      .insert(users)
      .values({
        id: userId,
        email: `${userId}@autogenerated.daystash.local`,
        createdAt: new Date(),
        updatedAt: new Date(),
      })
      .onConflictDoNothing({ target: users.id });

    const serverTransactionTime = new Date();
    const appliedRecordIds: string[] = [];
    const conflicts: SyncConflict[] = [];
    const pendingJobUpdates: PendingJobUpdate[] = [];

    // 3. Process client mutations inside an ACID transaction
    await db.transaction(async (tx) => {
      for (const mutation of mutations) {
        // Query existing record on server
        const [existing] = await tx
          .select()
          .from(reminders)
          .where(and(eq(reminders.id, mutation.id), eq(reminders.userId, userId)));

        if (!existing) {
          // Record does not exist on server: insert brand new reminder
          const initialVersion = Math.max(1, mutation.version);
          const nextTriggerDate = mutation.nextTriggerUtc
            ? new Date(mutation.nextTriggerUtc)
            : null;
          const deletedAtDate = mutation.deletedAt
            ? new Date(mutation.deletedAt)
            : null;

          await tx.insert(reminders).values({
            id: mutation.id,
            userId,
            title: mutation.title,
            notes: mutation.notes ?? null,
            rrule: mutation.rrule ?? null,
            timezone: mutation.timezone,
            nextTriggerUtc: nextTriggerDate,
            status: mutation.status,
            version: initialVersion,
            createdAt: new Date(mutation.createdAt),
            updatedAt: serverTransactionTime,
            deletedAt: deletedAtDate,
          });

          appliedRecordIds.push(mutation.id);
          pendingJobUpdates.push({
            id: mutation.id,
            title: mutation.title,
            status: deletedAtDate ? 'ARCHIVED' : mutation.status,
            nextTriggerUtc: deletedAtDate ? null : nextTriggerDate,
          });
          continue;
        }

        // Existing record exists: apply Optimistic Concurrency Control (OCC)
        const clientVersion = mutation.version;
        const serverVersion = existing.version;
        const clientUpdatedAtMs = new Date(mutation.updatedAt).getTime();
        const serverUpdatedAtMs = new Date(existing.updatedAt).getTime();

        let shouldApply = false;

        if (clientVersion >= serverVersion) {
          // Rule 1: Version check passes
          shouldApply = true;
        } else if (clientUpdatedAtMs > serverUpdatedAtMs) {
          // Rule 2: Last-Write-Wins (LWW) timestamp fallback if client clock is newer
          shouldApply = true;
        }

        if (shouldApply) {
          const nextVersion = Math.max(serverVersion, clientVersion) + 1;
          const nextTriggerDate = mutation.nextTriggerUtc
            ? new Date(mutation.nextTriggerUtc)
            : null;
          const deletedAtDate = mutation.deletedAt
            ? new Date(mutation.deletedAt)
            : null;

          await tx
            .update(reminders)
            .set({
              title: mutation.title,
              notes: mutation.notes ?? null,
              rrule: mutation.rrule ?? null,
              timezone: mutation.timezone,
              nextTriggerUtc: nextTriggerDate,
              status: mutation.status,
              version: nextVersion,
              updatedAt: serverTransactionTime,
              deletedAt: deletedAtDate,
            })
            .where(and(eq(reminders.id, mutation.id), eq(reminders.userId, userId)));

          appliedRecordIds.push(mutation.id);

          // Track whether trigger timing, status, or soft-delete changed
          const statusChanged = existing.status !== mutation.status;
          const triggerChanged =
            (existing.nextTriggerUtc?.getTime() ?? null) !==
            (nextTriggerDate?.getTime() ?? null);
          const deleteChanged =
            (existing.deletedAt === null && deletedAtDate !== null) ||
            (existing.deletedAt !== null && deletedAtDate === null);

          if (statusChanged || triggerChanged || deleteChanged) {
            pendingJobUpdates.push({
              id: mutation.id,
              title: mutation.title,
              status: deletedAtDate ? 'ARCHIVED' : mutation.status,
              nextTriggerUtc: deletedAtDate ? null : nextTriggerDate,
            });
          }
        } else {
          // Conflict: server record is strictly newer than client mutation
          conflicts.push({
            id: mutation.id,
            reason: 'VERSION_CONFLICT',
            message: `Conflict: server version ${serverVersion} (updated ${existing.updatedAt.toISOString()}) is newer than client version ${clientVersion} (updated ${mutation.updatedAt})`,
            serverRecord: {
              id: existing.id,
              userId: existing.userId,
              title: existing.title,
              notes: existing.notes,
              rrule: existing.rrule,
              timezone: existing.timezone,
              nextTriggerUtc: existing.nextTriggerUtc
                ? existing.nextTriggerUtc.toISOString()
                : null,
              status: existing.status,
              version: existing.version,
              createdAt: existing.createdAt.toISOString(),
              updatedAt: existing.updatedAt.toISOString(),
              deletedAt: existing.deletedAt
                ? existing.deletedAt.toISOString()
                : null,
            },
          });
        }
      }
    });

    // 4. Update delayed BullMQ reminder scheduler jobs post-transaction
    for (const job of pendingJobUpdates) {
      if (
        job.status === 'ACTIVE' &&
        job.nextTriggerUtc &&
        job.nextTriggerUtc.getTime() > Date.now()
      ) {
        await scheduleReminderJob(job.id, userId, job.title, job.nextTriggerUtc);
      } else {
        await cancelReminderJob(job.id);
      }
    }

    // 5. Enqueue silent push notification to notify user's OTHER registered devices
    if (appliedRecordIds.length > 0) {
      const userDeviceList = await db
        .select()
        .from(userDevices)
        .where(eq(userDevices.userId, userId));

      if (userDeviceList.length > 0) {
        await enqueueSilentPushJob({
          userId,
          excludedDeviceId: deviceId,
          mutatedReminderIds: appliedRecordIds,
          timestamp: serverTransactionTime.toISOString(),
        });
      }
    }

    // 6. Query server delta records: all reminders updated_at > lastSyncedAt (including soft deletes)
    const deltaConditions = [eq(reminders.userId, userId)];
    if (lastSyncedAt) {
      deltaConditions.push(gt(reminders.updatedAt, new Date(lastSyncedAt)));
    }

    const deltaRows = await db
      .select()
      .from(reminders)
      .where(and(...deltaConditions));

    const serverDeltas: ReminderServerDelta[] = deltaRows.map((row) => ({
      id: row.id,
      userId: row.userId,
      title: row.title,
      notes: row.notes,
      rrule: row.rrule,
      timezone: row.timezone,
      nextTriggerUtc: row.nextTriggerUtc
        ? row.nextTriggerUtc.toISOString()
        : null,
      status: row.status,
      version: row.version,
      createdAt: row.createdAt.toISOString(),
      updatedAt: row.updatedAt.toISOString(),
      deletedAt: row.deletedAt ? row.deletedAt.toISOString() : null,
    }));

    const responsePayload: SyncResponse = {
      syncedAt: serverTransactionTime.toISOString(),
      appliedRecordIds,
      conflicts,
      serverDeltas,
    };

    return NextResponse.json(responsePayload, { status: 200 });
  } catch (error) {
    console.error('[API /api/sync] Internal Error:', error);
    return NextResponse.json(
      {
        error: 'Internal Server Error',
        message: error instanceof Error ? error.message : 'Unknown error',
      },
      { status: 500 }
    );
  }
}
